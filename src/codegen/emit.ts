import { outputChannel, workingChannel, type SkillNodeSpec, type WorkflowSpec } from "../pipeline/spec.js";
import {
  indent,
  literal,
  pascalCase,
  renderObjectSchema,
  renderTsType,
  templateLiteral,
} from "./render.js";

export interface EmitOptions {
  /** Absolute path to the installed j2 runtime entry point. */
  runtimePath: string;
  provider: string;
  j2Version: string;
  generatedAt: string;
}

/**
 * Renders a validated `WorkflowSpec` into a standalone TypeScript module.
 *
 * Nothing here is model-authored: the spec has already been through
 * `assembleWorkflow`, and every string that reaches the output goes through a
 * literal renderer. The emitted file is thin by design — the topology, the
 * schemas, and the prompts are data; all behaviour lives in the j2 runtime it
 * imports.
 */
export function emitWorkflow(spec: WorkflowSpec, options: EmitOptions): string {
  const parts = [
    header(spec, options),
    imports(options.runtimePath),
    meta(spec, options),
    ...spec.nodes.map(nodeTypes),
    stateSchema(spec),
    ...spec.nodes.map((node) => nodeDeclaration(node)),
    footer(spec),
  ];
  return `${parts.join("\n\n")}\n`;
}

function header(spec: WorkflowSpec, options: EmitOptions): string {
  return [
    `// Generated by j2 ${options.j2Version} on ${options.generatedAt}.`,
    `// Source skills: ${spec.source}`,
    `// Regenerate with: j2 generate --dir ${spec.source} --name ${spec.slug} --force`,
    "//",
    `// Ordering rationale: ${spec.rationale.replace(/\s+/g, " ")}`,
  ].join("\n");
}

function imports(runtimePath: string): string {
  return [
    "import {",
    "  z,",
    "  appended,",
    "  baseState,",
    "  buildWorkflow,",
    "  defineSkillNode,",
    "  lastValue,",
    "  workingEntrySchema,",
    "  type BuildOptions,",
    "  type WorkflowModule,",
    "  type WorkingEntry,",
    `} from ${literal(runtimePath)};`,
  ].join("\n");
}

function meta(spec: WorkflowSpec, options: EmitOptions): string {
  const entries = [
    `id: ${literal(spec.slug)}`,
    `title: ${literal(spec.title)}`,
    `description: ${literal(spec.description)}`,
    `setKind: ${literal(spec.setKind)}`,
    `order: [${spec.order.map(literal).join(", ")}]`,
    `provider: ${literal(options.provider)}`,
    `source: ${literal(spec.source)}`,
    `runtime: ${literal(options.runtimePath)}`,
    `j2Version: ${literal(options.j2Version)}`,
    `generatedAt: ${literal(options.generatedAt)}`,
  ];
  return `export const meta = {\n${entries.map((entry) => `  ${entry},`).join("\n")}\n} as const;`;
}

/** A node's output schema, its TypeScript type, and its context type. */
function nodeTypes(node: SkillNodeSpec): string {
  const output = `${pascalCase(node.id)}Output`;

  const fieldTypes = node.outputFields
    .map((field) => `  ${field.name}${field.optional ? "?" : ""}: ${renderTsType(field)};`)
    .join("\n");

  const contextType = [
    `/** Context assembled for the \`${node.id}\` node on every agent iteration. */`,
    `export type ${pascalCase(node.id)}Context = {`,
    "  /** Structured input, fixed when this workflow was generated. */",
    "  input: { whenToUse: string; produces: string; arguments: readonly { name: string; description: string; required: boolean }[]; files: readonly string[] };",
    "  /** Implicit input: output of the nodes this one reads. */",
    `  upstream: { ${node.reads.map((id) => `${id}: ${pascalCase(id)}Output`).join("; ")} };`,
    "  /** Working context: node-local and append-only. */",
    "  working: readonly WorkingEntry[];",
    "  /** Output context: what downstream nodes receive. */",
    `  output?: ${output};`,
    "  /** Related skills in this workflow. */",
    "  references: readonly { nodeId: string; description: string }[];",
    "};",
  ].join("\n");

  return [
    `export const ${output} = ${renderObjectSchema(node.outputFields)};`,
    `export type ${output} = {\n${fieldTypes}\n};`,
    contextType,
  ].join("\n\n");
}

function stateSchema(spec: WorkflowSpec): string {
  const channels = spec.nodes.flatMap((node) => [
    `  ${workingChannel(node.id)}: appended(workingEntrySchema),`,
    `  ${outputChannel(node.id)}: lastValue(${pascalCase(node.id)}Output),`,
  ]);
  return [
    "/** One channel per node, plus the channels every workflow shares. */",
    "export const State = z.object({",
    "  ...baseState,",
    ...channels,
    "});",
  ].join("\n");
}

function nodeDeclaration(node: SkillNodeSpec): string {
  const argumentLines = node.staticInput.arguments.map(
    (argument) =>
      `    { name: ${literal(argument.name)}, description: ${literal(argument.description)}, required: ${argument.required} },`,
  );
  const referenceLines = node.references.map(
    (reference) =>
      `  { nodeId: ${literal(reference.nodeId)}, description: ${literal(reference.description)} },`,
  );

  const fields = [
    `id: ${literal(node.id)},`,
    `title: ${literal(node.title)},`,
    `size: ${literal(node.size)},`,
    `skillDir: ${literal(node.skillDir)},`,
    "staticInput: {",
    `  whenToUse: ${literal(node.staticInput.whenToUse)},`,
    `  produces: ${literal(node.staticInput.produces)},`,
    argumentLines.length ? `  arguments: [\n${argumentLines.join("\n")}\n  ],` : "  arguments: [],",
    `  files: [${node.staticInput.files.map(literal).join(", ")}],`,
    "},",
    referenceLines.length ? `references: [\n${referenceLines.join("\n")}\n],` : "references: [],",
    `reads: [${node.reads.map(literal).join(", ")}],`,
    `workingChannel: ${literal(workingChannel(node.id))},`,
    `outputChannel: ${literal(outputChannel(node.id))},`,
    `outputSchema: ${pascalCase(node.id)}Output,`,
    `tools: { allow: [${node.tools.allow.map(literal).join(", ")}], deny: [${node.tools.deny.map(literal).join(", ")}] },`,
    `maxIterations: ${node.maxIterations},`,
  ];

  // The prompt is appended after indentation: indenting a template literal
  // would rewrite the skill's own markdown, breaking its code blocks.
  return [
    `const ${node.id} = defineSkillNode({`,
    indent(fields.join("\n"), 2),
    `  systemPrompt: ${templateLiteral(systemPrompt(node))},`,
    "});",
  ].join("\n");
}

/**
 * The node's system prompt: the skill's own instructions verbatim, then the
 * generated guidance, then the contract the agent loop has to satisfy.
 */
function systemPrompt(node: SkillNodeSpec): string {
  const fields = node.outputFields
    .map((field) => `- ${field.name}${field.optional ? " (optional)" : ""}: ${field.description}`)
    .join("\n");

  const toolLine = node.tools.allow.length
    ? `You have these tools: ${node.tools.allow.join(", ")}.`
    : "You have no tools: reason from the context you are given.";

  const askLine = node.tools.allow.includes("ask_human")
    ? " Use ask_human whenever you need something only the user knows; ask one question at a time."
    : "";

  return [
    node.skillBody,
    "",
    "---",
    "",
    `# How this step fits the workflow`,
    node.systemGuidance,
    "",
    "# Operating rules",
    `${toolLine}${askLine}`,
    "All file paths are relative to the workspace root, and you cannot read or write outside it.",
    `You may take at most ${node.maxIterations} turns.`,
    "",
    "# Required result",
    "When the step is complete, return a structured result with these fields:",
    fields,
  ].join("\n");
}

function footer(spec: WorkflowSpec): string {
  return [
    `export const nodes = [${spec.nodes.map((node) => node.id).join(", ")}] as const;`,
    "",
    "const workflow: WorkflowModule<typeof State> = {",
    "  meta,",
    "  State,",
    "  nodes,",
    "  order: meta.order,",
    "  build: (options: BuildOptions) => buildWorkflow({ State, nodes, order: meta.order }, options),",
    "};",
    "",
    "export default workflow;",
  ].join("\n");
}
